#!/usr/bin/env node
// Regenerates verification evidence for a phase: `npm run verify -- phase-1`
//  - runs every acceptance scenario through the REAL headless CLI, saves scenario/inputs/out.jsonl
//  - runs a determinism check (two runs, sha256 compare)
//  - runs the full test suite and saves the report
//  - writes docs/proof/<phase>/results.md (generated, never hand-edited)
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { SCENARIOS } from '../tests/scenarios.mjs';
import { ROOT, runScenario } from '../tests/helpers.mjs';

const phase = process.argv[2] || 'phase-1';
const outDir = path.join(ROOT, 'docs', 'proof', phase);
const scDir = path.join(outDir, 'scenarios');
fs.rmSync(scDir, { recursive: true, force: true });
fs.mkdirSync(scDir, { recursive: true });

const rows = [];
let failed = 0;
for (const sc of SCENARIOS) {
  const dir = path.join(scDir, sc.name);
  const r = runScenario(sc, dir);
  let status = 'PASS';
  let note = '';
  try {
    if (r.code !== 0) throw new Error(`exit ${r.code}: ${r.stderr.trim()}`);
    sc.check(r.lines);
  } catch (e) {
    status = 'FAIL';
    note = e.message.split('\n')[0];
    failed++;
  }
  const endLine = r.lines.at(-1) ? JSON.stringify(r.lines.at(-1)) : '-';
  rows.push(`| ${sc.name} | ${sc.req} | \`${endLine}\` | **${status}** ${note} |`);
}

// determinism: default random world, same seed + inputs twice
const inputs = { frames: [{ tick: 0, move: [0, 1] }, { tick: 300, move: [1, 0.5], cam_yaw_deg: 60, pulse: true }, { tick: 301, pulse: false }] };
const hash = (t) => crypto.createHash('sha256').update(t).digest('hex');
const t1 = runScenario({ seed: 1234, ticks: 3600, inputs }, fs.mkdtempSync(path.join(os.tmpdir(), 'ddl-')));
const t2 = runScenario({ seed: 1234, ticks: 3600, inputs }, fs.mkdtempSync(path.join(os.tmpdir(), 'ddl-')));
const det = t1.outText === t2.outText && t1.outText.length > 0;
if (!det) failed++;

const test = spawnSync(process.execPath, ['--test'], { cwd: ROOT, encoding: 'utf8' });
fs.writeFileSync(path.join(outDir, 'test-report.txt'), test.stdout + test.stderr);
if (test.status !== 0) failed++;
const summary = (test.stdout.match(/^ℹ (tests|pass|fail) \d+$/gm) || []).join(', ');

const md = `# ${phase} — generated verification results

> Generated by \`npm run verify -- ${phase}\` on ${new Date().toISOString()} (Node ${process.version}, ${os.platform()} ${os.arch()}).
> Do not edit by hand. Each scenario folder holds the exact \`scenario.json\`, \`inputs.json\` and headless \`out.jsonl\`.

## Acceptance scenarios (real headless CLI)

| Scenario | Requirement checked | Final line of out.jsonl | Result |
|---|---|---|---|
${rows.join('\n')}

## Determinism

Seed 1234, 3600 ticks, same inputs, run twice: sha256 \`${hash(t1.outText).slice(0, 16)}…\` vs \`${hash(t2.outText).slice(0, 16)}…\` → **${det ? 'IDENTICAL (PASS)' : 'DIFFERENT (FAIL)'}**

## Full test suite (\`npm test\`)

Exit code ${test.status} — ${summary}. Full output: [test-report.txt](test-report.txt)
`;
fs.writeFileSync(path.join(outDir, 'results.md'), md);
console.log(md);
process.exit(failed ? 1 : 0);
